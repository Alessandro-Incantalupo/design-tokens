/**
 * surfaces.css, generated from the two theme files: an inverse surface is an area
 * in the other theme's colours (a dark call-to-action band on a light page, a light
 * one on a dark page). It re-sets every role inside it, so components placed there
 * keep using the same classes and stay readable.
 */
import { type Theme, type TokenModel } from './model.ts';

export const INVERSE = "[data-surface='inverse']";

/** The light (default) and dark themes; surfaces need exactly these two. */
export function lightAndDark(model: TokenModel): { light: Theme; dark: Theme } {
  const light = model.themes.find((t) => t.isDefault);
  const dark = model.themes.find((t) => t.name === 'dark');
  if (!light || !dark) throw new Error('Surfaces need a default theme and a dark theme');
  return { light, dark };
}

function block(selector: string, scheme: string, theme: Theme, indent = ''): string {
  const lines = [`${indent}${selector} {`, `${indent}  color-scheme: ${scheme};`];
  for (const [name, value] of theme.declarations) lines.push(`${indent}  ${name}: ${value};`);
  lines.push(`${indent}}`);
  return lines.join('\n');
}

export function surfacesCss(model: TokenModel): string {
  const { light, dark } = lightAndDark(model);
  return `/*
 * Inverse surface: an area in the other theme's colours. Generated by
 * \`pnpm tokens:build\` from themes/${light.name}.css and themes/dark.css; don't edit by hand.
 *
 *   <section data-surface="inverse">...</section>
 *
 * On a light page it takes the dark roles, on a dark page the light ones, so the
 * components inside keep their usual classes (bg-surface, text-default, border-border).
 * "The page" is the theme on <html> (or the system's, when <html> has no data-theme).
 * Inside a nested data-theme section, give the area its own data-theme instead.
 */
${block(INVERSE, 'dark', dark)}

${block(`:root[data-theme='dark'] ${INVERSE}`, 'light', light)}

@media (prefers-color-scheme: dark) {
${block(`:root:not([data-theme]) ${INVERSE}`, 'light', light, '  ')}
}
`;
}
